# -*- coding: utf-8 -*-
"""
Erzeugt src/Lernplattform.Core/Suche/PythonKlein.Tabelle.cs (Phase 2, Welle 3,
Paket L8): die Tabelle, mit der C# Pythons str.lower() nachbaut, statt
ToLowerInvariant zu nehmen (Weisung P2-7). Gerechnet mit Python 3.12 (wie die
Python-Linie v0.63.2 und der CI-Schritt "vergleichswerte", Unicode 15.0).

Inhalt:
  Laeufe      - je Lauf (Start, Anzahl, Schritt, Abstand): die Zeichen Start,
                Start + Schritt, ... werden zu Zeichen + Abstand (ein Zeichen).
  Mehrfach    - Zeichen, die zu mehreren Zeichen werden (nur U+0130 "İ").
  GrossKlein  - Bereiche "gross/klein und nicht uebergehbar" fuer das
                Schluss-Sigma, UEBERGEHBAR die uebergehbaren Zeichen
                (gemessen mit lower() selbst, siehe erzeuge_suche.py).

Ob die Tabelle stimmt, prueft der Test SucheTests gegen tests/Vergleich/suche.json
(G19, dort steht die volle Tabelle). Diese Datei wird nur neu erzeugt, wenn sich
die Python-Linie aendert (sie ist eingefroren).

Aufruf:
  python3.12 -I werkzeuge/tabellen/erzeuge_python_klein.py src/Lernplattform.Core/Suche/PythonKlein.Tabelle.cs
"""
import sys
import unicodedata


def zeichen():
    return (chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000)


def bereiche(werte):
    ergebnis = []
    for wert in werte:
        if ergebnis and ergebnis[-1][1] == wert - 1:
            ergebnis[-1][1] = wert
        else:
            ergebnis.append([wert, wert])
    return ergebnis


def zeilen(werte, je):
    teile = [", ".join(str(w) for w in werte[i:i + je]) for i in range(0, len(werte), je)]
    return ",\n        ".join(teile)


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    if sys.version_info[:2] != (3, 12):
        print("Bitte mit Python 3.12 erzeugen (Unicode wie die Python-Linie)")
        return 2
    laeufe, mehrfach = [], []
    for c in zeichen():
        klein = c.lower()
        if klein == c:
            continue
        if len(klein) != 1:
            mehrfach.append((ord(c), klein))
            continue
        code, abstand = ord(c), ord(klein) - ord(c)
        if laeufe:
            start, anzahl, schritt, letzter = laeufe[-1]
            if letzter == abstand and (anzahl == 1 and code - start in (1, 2)
                                       or anzahl > 1 and code == start + anzahl * schritt):
                laeufe[-1] = [start, anzahl + 1, code - start if anzahl == 1 else schritt, abstand]
                continue
        laeufe.append([code, 1, 1, abstand])

    def schluss(text):
        return text.lower()[-1:] == "ς"

    gross_klein = bereiche([ord(c) for c in zeichen() if schluss(c + "Σ")])
    uebergehbar = bereiche([ord(c) for c in zeichen() if schluss("A" + c + "Σ") and not schluss(c + "Σ")])

    text = []
    text.append("// <auto-generated>")
    text.append("// Erzeugt von werkzeuge/tabellen/erzeuge_python_klein.py mit Python %s (Unicode %s)."
                % (sys.version.split()[0], unicodedata.unidata_version))
    text.append("// Nicht von Hand aendern; geprueft gegen tests/Vergleich/suche.json (G19).")
    text.append("// </auto-generated>")
    text.append("namespace Lernplattform.Core.Suche;")
    text.append("")
    text.append("public static partial class PythonKlein")
    text.append("{")
    text.append("    /// <summary>Laeufe (Start, Anzahl, Schritt, Abstand) der Zeichen, die lower() zu einem Zeichen macht.</summary>")
    text.append("    private static readonly int[] Laeufe =")
    text.append("    [")
    text.append("        " + zeilen([w for lauf in laeufe for w in lauf], 12) + ",")
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Zeichen, die lower() zu mehreren Zeichen macht (Codepunkt, Ergebnis).</summary>")
    text.append("    private static readonly (int Zeichen, string Klein)[] Mehrfach =")
    text.append("    [")
    for code, klein in mehrfach:
        text.append("        (0x%04X, \"%s\")," % (code, "".join("\\u%04x" % ord(z) for z in klein)))
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Bereiche (von, bis) der Zeichen mit Gross-/Kleinschreibung, die nicht uebergangen werden (Final_Sigma).</summary>")
    text.append("    private static readonly int[] GrossKlein =")
    text.append("    [")
    text.append("        " + zeilen([w for b in gross_klein for w in b], 12) + ",")
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Bereiche (von, bis) der Zeichen, die das Schluss-Sigma uebergeht (case-ignorable).</summary>")
    text.append("    private static readonly int[] Uebergehbar =")
    text.append("    [")
    text.append("        " + zeilen([w for b in uebergehbar for w in b], 12) + ",")
    text.append("    ];")
    text.append("}")
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(text) + "\n")
    print("%d Laeufe, %d mehrfach, %d + %d Bereiche -> %s"
          % (len(laeufe), len(mehrfach), len(gross_klein), len(uebergehbar), sys.argv[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
