#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Erzeugt src/Lernplattform.Core/Projekt/PdfZeichen.Tabelle.cs (Phase 4, Welle 3,
Paket PB8): fuer jeden einzelnen Codepunkt das Ergebnis von fisi_pdf._clean
(Ersatztabelle _REPLACE, sonst _fallback: Emoji und Symbole entfallen, sonst die
Grundform nach NFKD, zuletzt "?"). Gerechnet mit Python 3.12 (Unicode 15.0) aus
dem eingefrorenen Stand v0.63.2, weil unicodedata (Kategorie, NFKD) an der
Unicode-Fassung haengt und .NET eine andere hat. Nur das NFC ueber den ganzen
Text macht C# selbst (string.Normalize).

Inhalt:
  Leer     - Bereiche (von, bis) der Zeichen, die entfallen
  Frage    - Bereiche (von, bis) der Zeichen, die zu "?" werden
  Einzeln  - alle anderen Zeichen, die sich aendern (Codepunkt, Ergebnis)
Alle uebrigen Zeichen bleiben gleich.

Ob die Tabelle stimmt, prueft AbschlussprojektPdfTests gegen
tests/Vergleich/abschlussprojekt.json (G34 Teil zeichen). Die CI erzeugt die
Datei neu und vergleicht.

Aufruf:
  python3.12 -I werkzeuge/tabellen/erzeuge_pdf_zeichen.py <pfad_fisi_lernplattform> src/Lernplattform.Core/Projekt/PdfZeichen.Tabelle.cs
"""
import sys
import unicodedata


def bereiche(werte):
    ergebnis = []
    for wert in werte:
        if ergebnis and ergebnis[-1][1] == wert - 1:
            ergebnis[-1][1] = wert
        else:
            ergebnis.append([wert, wert])
    return ergebnis


def zeilen(werte, je):
    teile = [", ".join(str(w) for w in werte[i:i + je]) for i in range(0, len(werte), je)]
    return ",\n        ".join(teile)


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    if sys.version_info[:2] != (3, 12):
        print("Bitte mit Python 3.12 erzeugen (Unicode wie die Python-Linie)")
        return 2
    sys.path.insert(0, sys.argv[1])
    import fisi_pdf
    leer, frage, einzeln = [], [], []
    for c in range(0x110000):
        if 0xD800 <= c < 0xE000:
            continue
        text = fisi_pdf._clean(chr(c))
        if text == chr(c):
            continue
        if text == "":
            leer.append(c)
        elif text == "?":
            frage.append(c)
        else:
            assert all(ord(z) < 0x10000 for z in text)
            einzeln.append((c, text))
    leer, frage = bereiche(leer), bereiche(frage)

    text = []
    text.append("// <auto-generated>")
    text.append("// Erzeugt von werkzeuge/tabellen/erzeuge_pdf_zeichen.py mit Python %s (Unicode %s)."
                % ("%d.%d" % sys.version_info[:2], unicodedata.unidata_version))
    text.append("// Nicht von Hand aendern; geprueft gegen tests/Vergleich/abschlussprojekt.json (G34).")
    text.append("// </auto-generated>")
    text.append("namespace Lernplattform.Core.Projekt;")
    text.append("")
    text.append("public static partial class PdfZeichen")
    text.append("{")
    text.append("    /// <summary>Bereiche (von, bis) der Zeichen, die _clean entfernt.</summary>")
    text.append("    private static readonly int[] Leer =")
    text.append("    [")
    text.append("        " + zeilen([w for b in leer for w in b], 12) + ",")
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Bereiche (von, bis) der Zeichen, die _clean zu \"?\" macht.</summary>")
    text.append("    private static readonly int[] Frage =")
    text.append("    [")
    text.append("        " + zeilen([w for b in frage for w in b], 12) + ",")
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Alle anderen Zeichen, die _clean aendert (Codepunkt, Ergebnis).</summary>")
    text.append("    private static readonly (int Zeichen, string Text)[] Einzeln =")
    text.append("    [")
    for code, ziel in einzeln:
        text.append("        (0x%04X, \"%s\")," % (code, "".join("\\u%04x" % ord(z) for z in ziel)))
    text.append("    ];")
    text.append("}")
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(text) + "\n")
    print("%d Bereiche leer, %d Bereiche ?, %d einzeln -> %s" % (len(leer), len(frage), len(einzeln), sys.argv[2]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
