#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Erzeugt src/Lernplattform.Core/Rechner/PythonZeichen.Tabelle.cs (Phase 3, Welle 1,
Paket R1): die Zeichentabellen, mit denen C# die Textregeln von Python nachbaut,
die die Rechner benutzen (Weisung P3-2, Plan Phase 3 Abschnitt 2.2). Gerechnet mit
Python 3.12 (wie die Python-Linie v0.63.2 und der CI-Schritt "vergleichswerte",
Unicode 15.0).

Inhalt:
  Ziffern     - Bereiche (von, bis) der Zeichen mit str.isdigit() (auch "²").
  Dezimal     - Bereiche (von, bis, Wert von "von") der Zeichen mit
                str.isdecimal(); so liest int() fremde Ziffern.
  Leerraum    - Zeichen mit str.isspace() (strip, split ohne Trenner).
  Zeilenende  - Zeichen, an denen str.splitlines() trennt ("\r\n" zaehlt einmal).
  FaltLaeufe  - str.casefold() wie PythonKlein.Laeufe (Start, Anzahl, Schritt,
                Abstand), FaltMehrfach die Zeichen mit mehreren Zeichen.

Ob die Tabelle stimmt, prueft RechnerZahlenTests gegen tests/Vergleich/rechner_zahlen.json
(G24, dort stehen die vollen Listen). Die CI erzeugt die Datei neu und vergleicht.

Aufruf:
  python3.12 -I werkzeuge/tabellen/erzeuge_python_zeichen.py src/Lernplattform.Core/Rechner/PythonZeichen.Tabelle.cs
"""
import sys
import unicodedata


def zeichen():
    return (chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000)


def bereiche(werte):
    ergebnis = []
    for wert in werte:
        if ergebnis and ergebnis[-1][1] == wert - 1:
            ergebnis[-1][1] = wert
        else:
            ergebnis.append([wert, wert])
    return ergebnis


def zeilen(werte, je):
    teile = [", ".join(str(w) for w in werte[i:i + je]) for i in range(0, len(werte), je)]
    return ",\n        ".join(teile)


def laeufe_von(abbildung):
    laeufe, mehrfach = [], []
    for c in zeichen():
        ziel = abbildung(c)
        if ziel == c:
            continue
        if len(ziel) != 1:
            mehrfach.append((ord(c), ziel))
            continue
        code, abstand = ord(c), ord(ziel) - ord(c)
        if laeufe:
            start, anzahl, schritt, letzter = laeufe[-1]
            if letzter == abstand and (anzahl == 1 and code - start in (1, 2)
                                       or anzahl > 1 and code == start + anzahl * schritt):
                laeufe[-1] = [start, anzahl + 1, code - start if anzahl == 1 else schritt, abstand]
                continue
        laeufe.append([code, 1, 1, abstand])
    return laeufe, mehrfach


def dezimal_bereiche():
    ergebnis = []
    for c in zeichen():
        if not c.isdecimal():
            continue
        wert = int(c)
        code = ord(c)
        if ergebnis and ergebnis[-1][1] == code - 1 and ergebnis[-1][2] + (code - ergebnis[-1][0]) == wert:
            ergebnis[-1][1] = code
        else:
            ergebnis.append([code, code, wert])
    return ergebnis


def zeilenenden():
    return [ord(c) for c in zeichen() if len(("a" + c + "b").splitlines()) > 1]


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    if sys.version_info[:2] != (3, 12):
        print("Bitte mit Python 3.12 erzeugen (Unicode wie die Python-Linie)")
        return 2
    ziffern = bereiche([ord(c) for c in zeichen() if c.isdigit()])
    dezimal = dezimal_bereiche()
    leer = [ord(c) for c in zeichen() if c.isspace()]
    enden = zeilenenden()
    falt, falt_mehr = laeufe_von(str.casefold)

    text = []
    text.append("// <auto-generated>")
    text.append("// Erzeugt von werkzeuge/tabellen/erzeuge_python_zeichen.py mit Python %s (Unicode %s)."
                % ("%d.%d" % sys.version_info[:2], unicodedata.unidata_version))
    text.append("// Nicht von Hand aendern; geprueft gegen tests/Vergleich/rechner_zahlen.json (G24).")
    text.append("// </auto-generated>")
    text.append("namespace Lernplattform.Core.Rechner;")
    text.append("")
    text.append("internal static partial class PythonZeichen")
    text.append("{")
    text.append("    /// <summary>Bereiche (von, bis) der Zeichen mit str.isdigit().</summary>")
    text.append("    private static readonly int[] Ziffern =")
    text.append("    [")
    text.append("        " + zeilen([w for b in ziffern for w in b], 12) + ",")
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Bereiche (von, bis, Wert von \"von\") der Zeichen mit str.isdecimal().</summary>")
    text.append("    private static readonly int[] Dezimal =")
    text.append("    [")
    text.append("        " + zeilen([w for b in dezimal for w in b], 12) + ",")
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Zeichen mit str.isspace().</summary>")
    text.append("    private static readonly int[] Leerraum =")
    text.append("    [")
    text.append("        " + zeilen(leer, 12) + ",")
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Zeichen, an denen str.splitlines() trennt.</summary>")
    text.append("    private static readonly int[] Zeilenende =")
    text.append("    [")
    text.append("        " + zeilen(enden, 12) + ",")
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Laeufe (Start, Anzahl, Schritt, Abstand) der Zeichen, die casefold() zu einem Zeichen macht.</summary>")
    text.append("    private static readonly int[] FaltLaeufe =")
    text.append("    [")
    text.append("        " + zeilen([w for lauf in falt for w in lauf], 12) + ",")
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Zeichen, die casefold() zu mehreren Zeichen macht (Codepunkt, Ergebnis).</summary>")
    text.append("    private static readonly (int Zeichen, string Gefaltet)[] FaltMehrfach =")
    text.append("    [")
    assert all(ord(z) < 0x10000 for _code, ziel in falt_mehr for z in ziel)
    for code, ziel in falt_mehr:
        text.append("        (0x%04X, \"%s\")," % (code, "".join("\\u%04x" % ord(z) for z in ziel)))
    text.append("    ];")
    text.append("}")
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(text) + "\n")
    print("%d + %d Bereiche, %d Leerraum, %d Zeilenenden, %d Laeufe, %d mehrfach -> %s"
          % (len(ziffern), len(dezimal), len(leer), len(enden), len(falt), len(falt_mehr), sys.argv[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
