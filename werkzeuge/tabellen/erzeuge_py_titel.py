"""
Erzeugt src/Lernplattform.Core/Spiel/PyTitel.Tabelle.cs (Phase 11 FW2, Sammelliste 80):
die Tabelle, mit der C# den ersten Buchstaben von Pythons str.capitalize() nachbaut
(Titelschreibung mit voller Zuordnung, z. B. "ß" -> "Ss", "ǆ" -> "ǅ", "ﬁ" -> "Fi"),
statt ToUpperInvariant zu nehmen. Den Rest kleinschreibt PythonKlein (str.lower()).
Gerechnet mit Python 3.12 (wie die Python-Linie v0.63.2, Unicode 15.0).

Inhalt:
  Laeufe   - je Lauf (Start, Anzahl, Schritt, Abstand): die Zeichen Start,
             Start + Schritt, ... werden zu Zeichen + Abstand (ein Zeichen).
  Mehrfach - Zeichen, deren Titelschreibung mehrere Zeichen hat.

Die CI erzeugt die Datei neu und vergleicht sie bytegleich (Schritt "vergleichswerte").

Aufruf:
  python3.12 -I werkzeuge/tabellen/erzeuge_py_titel.py src/Lernplattform.Core/Spiel/PyTitel.Tabelle.cs
"""
import sys
import unicodedata


def zeichen():
    return (chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000)


def zeilen(werte, je):
    teile = [", ".join(str(w) for w in werte[i:i + je]) for i in range(0, len(werte), je)]
    return ",\n        ".join(teile)


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    if sys.version_info[:2] != (3, 12):
        print("Bitte mit Python 3.12 erzeugen (Unicode wie die Python-Linie)")
        return 2
    laeufe, mehrfach = [], []
    for c in zeichen():
        # capitalize() eines einzelnen Zeichens = seine Titelschreibung (volle Zuordnung)
        titel = c.capitalize()
        if titel == c:
            continue
        if len(titel) != 1:
            mehrfach.append((ord(c), titel))
            continue
        code, abstand = ord(c), ord(titel) - ord(c)
        if laeufe:
            start, anzahl, schritt, letzter = laeufe[-1]
            if letzter == abstand and (anzahl == 1 and code - start in (1, 2)
                                       or anzahl > 1 and code == start + anzahl * schritt):
                laeufe[-1] = [start, anzahl + 1, code - start if anzahl == 1 else schritt, abstand]
                continue
        laeufe.append([code, 1, 1, abstand])

    text = []
    text.append("// <auto-generated>")
    text.append("// Erzeugt von werkzeuge/tabellen/erzeuge_py_titel.py mit Python %s (Unicode %s)."
                % ("%d.%d" % sys.version_info[:2], unicodedata.unidata_version))
    text.append("// Nicht von Hand aendern; die CI erzeugt die Datei neu und vergleicht sie bytegleich.")
    text.append("// </auto-generated>")
    text.append("namespace Lernplattform.Core.Spiel;")
    text.append("")
    text.append("public static partial class PyTitel")
    text.append("{")
    text.append("    /// <summary>Laeufe (Start, Anzahl, Schritt, Abstand) der Zeichen, deren Titelschreibung ein Zeichen ist.</summary>")
    text.append("    private static readonly int[] Laeufe =")
    text.append("    [")
    text.append("        " + zeilen([w for lauf in laeufe for w in lauf], 12) + ",")
    text.append("    ];")
    text.append("")
    text.append("    /// <summary>Zeichen, deren Titelschreibung mehrere Zeichen hat (Codepunkt, Ergebnis).</summary>")
    text.append("    private static readonly (int Zeichen, string Titel)[] Mehrfach =")
    text.append("    [")
    for code, titel in mehrfach:
        text.append("        (0x%04X, \"%s\")," % (code, "".join("\\u%04x" % ord(z) for z in titel)))
    text.append("    ];")
    text.append("}")
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(text) + "\n")
    print("%d Laeufe, %d mehrfach -> %s" % (len(laeufe), len(mehrfach), sys.argv[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
